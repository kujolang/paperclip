import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { abilityDefinitionDigestV2 } from "../bundled/ability-contract/index.ts";
const root = new URL("../", import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, root), "utf8"));
const lock = await read("bundled/ability-sources.lock.json");
for (const source of lock.sources) for (const file of source.files) {
  const bytes = await readFile(new URL(file.path, root));
  if (createHash("sha256").update(bytes).digest("hex") !== file.sha256) throw new Error(`Ability source checksum mismatch: ${file.path}`);
}
const canonical = await read("bundled/ability-catalog/abilities.json");
const profiles = await read("bundled/ability-catalog/profiles.json");
const projections = await read("src/abilities/projections.json");
const known = new Set();
const digest = (definition) => {
  const result = abilityDefinitionDigestV2(definition);
  if (!result.ok) throw new Error(`${definition.id}: ${result.message}`);
  return result.value;
};
const canonicalDefinitions = canonical.map(({ definition, source }) => {
  if (known.has(definition.id)) throw new Error(`Duplicate canonical identity: ${definition.id}`);
  known.add(definition.id);
  return { definition, definitionDigest: digest(definition), source: source ?? "ability" };
});
const resolveProfile = (id, stack = []) => {
  if (stack.includes(id)) throw new Error(`Profile inheritance cycle: ${id}`);
  const profile = profiles.find((item) => item.id === id);
  if (!profile || profile.schema !== "kujo.ability-profile/v1") throw new Error(`Invalid profile: ${id}`);
  const ids = [...new Set([...profile.extends.flatMap((parent) => resolveProfile(parent, [...stack, id])), ...profile.ability_ids])];
  for (const ability of ids) if (!known.has(ability)) throw new Error(`Unknown profile Ability: ${ability}`);
  return ids;
};
if (new Set(profiles.map((item) => item.id)).size !== profiles.length) throw new Error("Duplicate profile identity");
const compiledProfiles = profiles.map((profile) => ({ ...profile, resolvedAbilityIds: resolveProfile(profile.id) }));
const toolNames = new Set(), exportNames = new Set(), adapterIds = new Set();
const compiled = projections.map((projection) => {
  for (const id of projection.canonicalIds) if (!known.has(id)) throw new Error(`Unknown canonical binding: ${id}`);
  if (toolNames.has(projection.tool.name) || exportNames.has(projection.exportName) || adapterIds.has(projection.id)) throw new Error("Duplicate Paperclip projection");
  if (!/^[a-zA-Z][a-zA-Z0-9]+$/.test(projection.exportName)) throw new Error("Invalid projection export name");
  toolNames.add(projection.tool.name); exportNames.add(projection.exportName); adapterIds.add(projection.id);
  if (projection.id !== projection.definition.id || JSON.stringify(projection.tool.parametersSchema) !== JSON.stringify(projection.definition.input_schema)) throw new Error(`Projection schema drift: ${projection.id}`);
  return { ...projection, definitionDigest: digest(projection.definition), canonicalDefinitions: projection.canonicalIds.map((id) => canonicalDefinitions.find((entry) => entry.definition.id === id)) };
});
const output = `// Generated by scripts/generate-abilities.mjs. Edit projections.json or sync pinned sources.\n` +
  `export const canonicalDefinitions = ${JSON.stringify(canonicalDefinitions, null, 2)} as const;\n` +
  `export const canonicalProfiles = ${JSON.stringify(compiledProfiles, null, 2)} as const;\n` +
  `export const projections = ${JSON.stringify(compiled, null, 2)} as const;\n` +
  compiled.map((entry, index) => `export const ${entry.exportName} = projections[${index}].tool;`).join("\n") + "\n" +
  `export const projectedTools = projections.map((entry) => entry.tool);\n`;
const path = new URL("src/abilities/generated.ts", root);
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8").catch(() => "") !== output) throw new Error("Ability projection drift; run npm run abilities:generate");
} else await writeFile(path, output);
console.log(`Verified ${canonicalDefinitions.length} canonical definitions, ${profiles.length} profiles and ${compiled.length} Paperclip projections.`);
